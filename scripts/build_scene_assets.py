"""Generate the visitor scene fallback stylesheet and verify its contrast report."""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from reponpc.scene.registry import (  # noqa: E402
    SceneRegistryError,
    contrast_report,
    default_scene_registry,
    fallback_stylesheet,
)

OUTPUT = ROOT / "apps" / "web" / "src" / "app" / "scene-fallback.generated.css"


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="compare the checked-in fallback with generated bytes without writing",
    )
    args = parser.parse_args()
    try:
        registry = default_scene_registry()
        expected = fallback_stylesheet(registry)
    except SceneRegistryError as exc:
        print(f"scene registry invalid: {exc}", file=sys.stderr)
        return 1

    if args.check:
        try:
            current = OUTPUT.read_bytes()
        except OSError:
            current = None
        if current != expected:
            print(f"generated scene fallback is stale: {OUTPUT.relative_to(ROOT)}", file=sys.stderr)
            return 1
    else:
        OUTPUT.parent.mkdir(parents=True, exist_ok=True)
        OUTPUT.write_bytes(expected)

    print(
        json.dumps(
            contrast_report(registry), ensure_ascii=False, sort_keys=True, separators=(",", ":")
        )
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
