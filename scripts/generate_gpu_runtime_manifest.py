"""Regenerate src/reponpc/providers/gpu_runtime_manifest.yml (ADR-084).

The GPU runtime is the `onnxruntime-gpu` wheel that matches the pinned CPU
`onnxruntime` version, plus the NVIDIA runtime wheels it needs. This script
resolves them with `uv`, asks PyPI for each wheel's URL, size and SHA-256, and
writes the pinned manifest. It needs `uv` and network access to pypi.org.

    uv run python scripts/generate_gpu_runtime_manifest.py [--check]

`--check` regenerates in memory and exits 1 if the committed file differs.
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
import urllib.request
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
MANIFEST = ROOT / "src" / "reponpc" / "providers" / "gpu_runtime_manifest.yml"
PYTHON_TAG = "cp314"
PLATFORM_TAG = "win_amd64"
# CUDA 13 wheels: NVIDIA's CUDA 13.0 release notes (driver >= 580, Turing or newer).
MIN_DRIVER_MAJOR = 580
MIN_COMPUTE_CAPABILITY = "7.5"
# Already installed by the CPU `onnxruntime` dependency, so not part of the runtime.
SHARED = {"flatbuffers", "numpy", "packaging", "protobuf"}
HEADER = "# Generated by scripts/generate_gpu_runtime_manifest.py (ADR-084). Do not edit by hand.\n"


def _onnxruntime_version() -> str:
    match = re.search(r'"onnxruntime==([0-9.]+)"', (ROOT / "pyproject.toml").read_text("utf-8"))
    if match is None:
        raise SystemExit("pyproject.toml does not pin onnxruntime exactly")
    return match.group(1)


def _resolve(version: str) -> list[tuple[str, str]]:
    with tempfile.TemporaryDirectory() as folder:
        source = Path(folder) / "in.txt"
        source.write_text(f"onnxruntime-gpu[cuda,cudnn]=={version}\n", encoding="utf-8")
        result = subprocess.run(
            [
                "uv",
                "pip",
                "compile",
                str(source),
                "--python-platform",
                "windows",
                "--python-version",
                "3.14",
                "--no-header",
                "--no-annotate",
            ],
            check=True,
            capture_output=True,
            text=True,
        )
    pins = [tuple(line.split("==", 1)) for line in result.stdout.split() if "==" in line]
    pins = [(name, pin) for name, pin in pins if name not in SHARED]
    names = {name for name, _ in pins}
    unexpected = {n for n in names if n != "onnxruntime-gpu" and not n.startswith("nvidia-")}
    if "onnxruntime-gpu" not in names or unexpected:
        raise SystemExit(f"unexpected dependency set: {sorted(names)}")
    return sorted(pins)


def _wheel(name: str, version: str) -> dict[str, object]:
    url = f"https://pypi.org/pypi/{name}/{version}/json"
    with urllib.request.urlopen(url, timeout=60) as response:
        files = json.load(response)["urls"]
    suffix = (
        f"-{PYTHON_TAG}-{PYTHON_TAG}-{PLATFORM_TAG}.whl"
        if name == "onnxruntime-gpu"
        else f"-py3-none-{PLATFORM_TAG}.whl"
    )
    found = [f for f in files if f["filename"].endswith(suffix) and not f.get("yanked")]
    if len(found) != 1:
        raise SystemExit(f"{name}=={version}: expected one {suffix} wheel, found {len(found)}")
    item = found[0]
    return {
        "name": item["filename"],
        "url": item["url"],
        "bytes": item["size"],
        "sha256": item["digests"]["sha256"],
    }


def build() -> str:
    version = _onnxruntime_version()
    wheels = [_wheel(name, pin) for name, pin in _resolve(version)]
    document = {
        "schema_version": 1,
        "runtime_id": f"ort-{version}-cuda13-{PYTHON_TAG}-{PLATFORM_TAG}",
        "onnxruntime_version": version,
        "python_tag": PYTHON_TAG,
        "platform_tag": PLATFORM_TAG,
        "min_driver_major": MIN_DRIVER_MAJOR,
        "min_compute_capability": MIN_COMPUTE_CAPABILITY,
        "wheels": wheels,
    }
    return HEADER + yaml.safe_dump(document, sort_keys=False, width=200)


def main() -> int:
    text = build()
    if "--check" in sys.argv[1:]:
        return 0 if MANIFEST.read_text("utf-8") == text else 1
    MANIFEST.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {MANIFEST.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
