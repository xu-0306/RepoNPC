"""Compile untrusted visitor text into a deliberately small FTS5 query language.

SQLite FTS5 accepts a rich query syntax. The public question must never be
treated as that syntax, so this module returns either a parameter value for a
bounded exact-value fallback or a query made exclusively of generated quoted
phrases joined by generated ``AND`` operators. For a zero-result question
containing non-ASCII natural-language runs, it also prepares bounded
trigram phrase parameters and short exact values. The caller may use those
generated parameters as one recovery search; they never contain caller-
supplied FTS syntax.
"""

from __future__ import annotations

import re
import unicodedata
from dataclasses import dataclass
from enum import StrEnum

MIN_FTS_QUERY_CHARACTERS = 3
MAX_FTS_TERMS = 32
MAX_FTS_TERM_CHARACTERS = 128


class FtsQueryMode(StrEnum):
    """The safe retrieval mode chosen for normalized visitor text."""

    NO_QUERY = "no_query"
    SHORT_EXACT = "short_exact"
    MATCH = "match"


@dataclass(frozen=True, slots=True)
class CompiledFtsQuery:
    """A safe FTS5 ``MATCH`` parameter or a literal short-value fallback.

    ``match_expression`` is always generated by this module. Callers pass it
    as a bound SQLite value and must not concatenate it into SQL.

    ``fallback_fragments`` contains generated query values, their normalized-
    text positions, and their character width. Width three values are quoted
    FTS phrases; width two values are bound to the existing exact search.
    ASCII terms contribute independent rankings; required path phrases filter
    every fallback channel before its candidate limit.
    """

    mode: FtsQueryMode
    normalized_text: str
    terms: tuple[str, ...]
    match_expression: str | None
    exact_value: str | None
    fallback_fragments: tuple[tuple[str, int, int], ...] = ()
    fallback_ascii_terms: tuple[str, ...] = ()
    fallback_required_expression: str | None = None


def compile_fts_query(question: str) -> CompiledFtsQuery:
    """Compile untrusted text without allowing any caller-supplied FTS syntax.

    Empty or control-only input produces :attr:`FtsQueryMode.NO_QUERY`.
    Questions shorter than three normalized Unicode scalar values use the
    caller's bounded exact-value fallback. Other input becomes a conjunction
    of generated, quoted phrases; user quotation marks are removed before
    query generation so no user character can terminate a generated phrase.

    Raises:
        TypeError: If ``question`` is not text.
        ValueError: If the input exceeds the primitive's bounded term limits.
    """
    if not isinstance(question, str):
        raise TypeError("question must be a string")

    normalized = _normalize_question(question)
    if not normalized:
        return CompiledFtsQuery(
            mode=FtsQueryMode.NO_QUERY,
            normalized_text="",
            terms=(),
            match_expression=None,
            exact_value=None,
        )

    if len(normalized) < MIN_FTS_QUERY_CHARACTERS:
        return CompiledFtsQuery(
            mode=FtsQueryMode.SHORT_EXACT,
            normalized_text=normalized,
            terms=(normalized,),
            match_expression=None,
            exact_value=normalized,
        )

    terms = _compile_terms(normalized)
    if not terms:
        return CompiledFtsQuery(
            mode=FtsQueryMode.NO_QUERY,
            normalized_text=normalized,
            terms=(),
            match_expression=None,
            exact_value=None,
        )

    ascii_terms, required = _compile_fallback_ascii(normalized)
    return CompiledFtsQuery(
        mode=FtsQueryMode.MATCH,
        normalized_text=normalized,
        terms=terms,
        match_expression=" AND ".join(_quote_phrase(term) for term in terms),
        exact_value=None,
        fallback_fragments=_compile_fallback_fragments(
            normalized, limit=MAX_FTS_TERMS - len(ascii_terms) - len(required)
        ),
        fallback_ascii_terms=ascii_terms,
        fallback_required_expression=" AND ".join(required) or None,
    )


def _normalize_question(question: str) -> str:
    """Normalize to NFC, replacing every Unicode control with one separator."""
    nfc_question = unicodedata.normalize("NFC", question)
    without_controls = "".join(
        " " if unicodedata.category(character).startswith("C") else character
        for character in nfc_question
    )
    return " ".join(without_controls.split())


def _compile_terms(normalized: str) -> tuple[str, ...]:
    """Retain bounded searchable fragments while stripping phrase delimiters."""
    terms: list[str] = []
    for raw_term in normalized.split(" "):
        # A user quote is the one FTS5 phrase delimiter. Dropping it before
        # wrapping the term in a generated quote makes phrase termination
        # impossible, even when the question is deliberately injection-shaped.
        term = raw_term.replace('"', "").replace("*", "")
        if not any(character.isalnum() for character in term):
            continue
        if len(term) > MAX_FTS_TERM_CHARACTERS:
            raise ValueError("query terms must not exceed 128 characters")
        terms.append(term)
        if len(terms) > MAX_FTS_TERMS:
            raise ValueError("query must not contain more than 32 searchable terms")
    return tuple(terms)


def _quote_phrase(term: str) -> str:
    """Quote a compiler-produced term that cannot contain phrase delimiters."""
    return f'"{term}"'


def _compile_fallback_ascii(normalized: str) -> tuple[tuple[str, ...], tuple[str, ...]]:
    """Separate structural paths from optional ASCII ranking channels."""
    terms: list[str] = []
    required: list[str] = []
    for match in re.finditer(r"[A-Za-z0-9_./\\-]+", normalized):
        value = match.group().strip(".-")
        if len(value) < 2 or not any(character.isalnum() for character in value):
            continue
        target = (
            required if "/" in value or "\\" in value or re.search(r"\w+\.\w+", value) else terms
        )
        phrase = _quote_phrase(value)
        if phrase not in target:
            target.append(phrase)
    # Reserve a non-ASCII channel; never discard a required path to fit the budget.
    return tuple(terms[: max(0, MAX_FTS_TERMS - len(required) - 1)]), tuple(required)


def _compile_fallback_fragments(normalized: str, *, limit: int) -> tuple[tuple[str, int, int], ...]:
    """Generate one bounded recovery representation for unspaced CJK text.

    Width-three windows are standard sliding trigrams for the existing
    trigram FTS table. Width-two windows use the existing exact ``instr``
    search and are sampled evenly within each span so a later subject is not
    lost to a prefix-only round-robin. Both forms are generated values, and
    the existing term limit bounds their combined count without adding a
    setting.
    """
    spans = _non_ascii_spans(normalized)
    short_budget = max(1, limit // len(spans)) if spans else 0
    fragments_by_span: list[tuple[tuple[str, int, int], ...]] = []
    for span, start in spans:
        short_fragments = _sample_fragments(
            tuple((span[index : index + 2], start + index, 2) for index in range(len(span) - 1)),
            limit=short_budget,
        )
        trigram_fragments = tuple(
            (_quote_phrase(span[index : index + MIN_FTS_QUERY_CHARACTERS]), start + index, 3)
            for index in range(len(span) - MIN_FTS_QUERY_CHARACTERS + 1)
        )
        combined: list[tuple[str, int, int]] = []
        for offset in range(max(len(short_fragments), len(trigram_fragments))):
            if offset < len(short_fragments):
                combined.append(short_fragments[offset])
            if offset < len(trigram_fragments):
                combined.append(trigram_fragments[offset])
        if combined:
            fragments_by_span.append(tuple(combined))

    selected: list[tuple[str, int, int]] = []
    seen: set[tuple[str, int]] = set()
    offset = 0
    while len(selected) < limit:
        available = False
        for span_fragments in fragments_by_span:
            if offset >= len(span_fragments):
                continue
            available = True
            fragment = span_fragments[offset]
            fragment_key = (fragment[0], fragment[2])
            if fragment_key not in seen:
                seen.add(fragment_key)
                selected.append(fragment)
            if len(selected) == limit:
                break
        if not available:
            break
        offset += 1
    return tuple(selected)


def _non_ascii_spans(normalized: str) -> tuple[tuple[str, int], ...]:
    spans: list[tuple[str, int]] = []
    current: list[str] = []
    start = 0
    for position, character in enumerate(normalized):
        if not character.isascii() and character.isalnum():
            if not current:
                start = position
            current.append(character)
            continue
        if current:
            spans.append(("".join(current), start))
            current.clear()
    if current:
        spans.append(("".join(current), start))
    return tuple(spans)


def _sample_fragments(
    fragments: tuple[tuple[str, int, int], ...], *, limit: int
) -> tuple[tuple[str, int, int], ...]:
    """Keep evenly spaced short windows within the shared fragment budget."""

    if len(fragments) <= limit:
        return fragments
    if limit <= 1:
        return fragments[:1]
    last = len(fragments) - 1
    return tuple(fragments[(index * last + limit - 2) // (limit - 1)] for index in range(limit))
